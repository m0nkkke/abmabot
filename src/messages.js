function buildPrivacyText({ operatorName, privacyContact, privacyPolicyUrl }) {
  if (privacyPolicyUrl) {
    return [
      'Информация об обработке персональных данных',
      '',
      `Оператор: ${operatorName}.`,
      `Документ об обработке персональных данных: ${privacyPolicyUrl}`,
      `Отзыв согласия и вопросы по персональным данным: ${privacyContact}.`,
      '',
      'Команда /revoke удаляет локальный профиль, сессию и отметку согласия в боте. Записи, уже переданные в Google Sheets, обрабатываются оператором по внутреннему регламенту.'
    ].join('\n');
  }

  return [
    'Информация об обработке персональных данных',
    '',
    `Оператор: ${operatorName}.`,
    'Цель обработки: идентификация сотрудника и фиксация сообщений о нарушениях на кассах самообслуживания.',
    'Обрабатываемые данные: MAX user_id, ФИО сотрудника, выбранные регион и магазин, дата события, сведения из формы сообщения и текстовые отчеты.',
    'Действия с данными: сбор, запись, систематизация, хранение, использование, передача в Google Sheets для ведения журнала сообщений и отчетов.',
    'Срок хранения определяется локальными документами оператора.',
    `Отзыв согласия и вопросы по персональным данным: ${privacyContact}.`,
    '',
    'Команда /revoke удаляет локальный профиль, сессию и отметку согласия в боте. Записи, уже переданные в Google Sheets, обрабатываются оператором по внутреннему регламенту.'
  ].join('\n');
}

function buildConsentText(config) {
  if (config.privacyPolicyUrl) {
    return [
      'Перед началом работы подтвердите согласие на обработку персональных данных.',
      '',
      `Документ об обработке персональных данных: ${config.privacyPolicyUrl}`,
      `Оператор: ${config.operatorName}.`,
      `Контакт по вопросам персональных данных: ${config.privacyContact}.`,
      '',
      'Нажимая «Согласен», вы подтверждаете согласие на обработку персональных данных согласно документу по ссылке.'
    ].join('\n');
  }

  return [
    'Перед началом работы подтвердите согласие на обработку персональных данных.',
    '',
    buildPrivacyText(config),
    '',
    'Нажимая «Согласен», вы подтверждаете согласие на указанную обработку персональных данных.'
  ].join('\n');
}

